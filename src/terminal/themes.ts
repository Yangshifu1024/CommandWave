import type { ITheme } from "@xterm/xterm";

/** Where a built-in theme came from and the license it ships under. */
export interface ThemeCredit {
  source: string;
  /** SPDX id, or "original" for themes authored in this repository. */
  license: string;
}

export interface ThemeDef {
  name: string;
  dark: boolean;
  /** Upstream project + license. Every theme carries one; see THIRD-PARTY-NOTICES.md. */
  credit: ThemeCredit;
  /** "legacy" = shipped before the licensing audit; "added" = audited in that pass. */
  group: "legacy" | "added";
  theme: ITheme;
}

