/**
 * Themes dropped in the licensing audit, mapped to the built-in that replaces
 * them. `null` means "no credible same-family replacement": those fall back to
 * the default theme. Recorded in THIRD-PARTY-NOTICES.md.
 */
export const removedThemeAliases: Record<string, string | null> = {
  Nord: "Nordfox",
  "Dark Pastel": null,
  "Tango Light": null,
  "Light Background": null,
};

/**
 * Rewrite a persisted theme name that no longer exists. Returns the replacement
 * name, or null when the stored name is still valid (nothing to migrate).
 */
export function migrateThemeName(name: string | null | undefined): string | null {
  if (!name) return null;
  if (themes.some((t) => t.name === name)) return null;
  return removedThemeAliases[name] ?? themes[0].name;
}
